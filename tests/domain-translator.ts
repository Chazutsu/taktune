export function jaDomainTranslator(
	key: string,
	params: Record<string, unknown> = {},
	fallback = key,
) {
	return Object.entries(params).reduce(
		(text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
		messages[key] ?? fallback,
	);
}
